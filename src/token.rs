mod tests {
    use super::*;

    /// Fixture generated by:
    ///
    /// ```js
    /// const crypto = require('crypto');
    /// const key = Buffer.from('this-is-a-32-byte-test-key!12345');
    /// const iv = Buffer.from('AAAAAAAAAAAAAAAA');
    /// const inner = { connection: { type: 'vnc', settings: {
    ///     hostname: '10.0.0.42', username: 'kasm_user',
    ///     password: 'secretsecret', port: 5901,
    ///     'disable-copy': 'false', 'disable-paste': 'false' } } };
    /// const c = crypto.createCipheriv('aes-256-cbc', key, iv);
    /// const enc = Buffer.concat([c.update(JSON.stringify(inner), 'utf8'), c.final()]);
    /// const env = { iv: iv.toString('base64'), value: enc.toString('base64') };
    /// console.log(Buffer.from(JSON.stringify(env)).toString('base64'));
    /// ```
    const KEY: &[u8; 32] = b"this-is-a-32-byte-test-key!12345";
    const TOKEN: &str = "eyJpdiI6IlFVRkJRVUZCUVVGQlFVRkJRVUZCUVE9PSIsInZhbHVlIjoiUGd0ZXJ3SmREdE9MenhBSWlpeGM3UUxHTm1VbEsxVHVZWG1PZ09PY3NkbUoxam9JcGVtNnVCbVdKdTlNR3VTZ0grajBYRDk5akdFWm9UNGd3Z2RGMTVtWkQ3bjZxamJlTWY4UnJ5dUNKQUxvaFZLSFpod25HaHBxelVqRFdCRHdFSk5IOWpBcktESnp2L0RMY29BczJ2WUpsenluaE16bXUzR3hQb3Q2YnY1VHJlK05COEd2Wm5tUUlyVnRUZ0M5SjRiZ0xsRXEzb3E4RFFKczNPTFgvaFd1WWs4RE85WWMycDJvZUtBbkd2ND0ifQ==";

    #[test]
    fn decrypts_known_node_fixture() {
        let conn = decrypt_token(TOKEN, KEY).expect("decrypt should succeed");
        assert_eq!(conn.kind, ConnectionKind::Vnc);
        assert_eq!(conn.hostname, "10.0.0.42");
        assert_eq!(conn.port, 5901);
        assert_eq!(conn.username.as_deref(), Some("kasm_user"));
        assert_eq!(conn.password.as_deref(), Some("secretsecret"));
    }

    #[test]
    fn rejects_wrong_key() {
        let mut bad = *KEY;
        bad[0] ^= 0x01;
        let result = decrypt_token(TOKEN, &bad);
        assert!(result.is_err(), "wrong key should fail decryption");
    }

    #[test]
    fn rejects_garbage_outer_base64() {
        let result = decrypt_token("!!!not-base64!!!", KEY);
        assert!(result.is_err());
    }

    #[test]
    fn rejects_wrong_size_iv() {
        // Build an envelope with a 4-byte IV instead of 16.
        let envelope = serde_json::json!({
            "iv": B64.encode([0u8; 4]),
            "value": B64.encode([0u8; 16]),
        });
        let token = B64.encode(serde_json::to_vec(&envelope).unwrap());
        let result = decrypt_token(&token, KEY);
        assert!(result.is_err());
    }

    #[test]
    fn protocol_name_matches_guacd_keys() {
        assert_eq!(ConnectionKind::Vnc.protocol_name(), "vnc");
        assert_eq!(ConnectionKind::Rdp.protocol_name(), "rdp");
        assert_eq!(ConnectionKind::Ssh.protocol_name(), "ssh");
    }
}
